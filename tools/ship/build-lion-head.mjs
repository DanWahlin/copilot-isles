#!/usr/bin/env node
import { NodeIO } from '@gltf-transform/core';
import { promises as fs } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';

const root = path.resolve(new URL('../..', import.meta.url).pathname);
const inDir = path.join(root, 'tools/ship/source/lion-head/lods');
const outDir = path.join(root, 'public/packs/testcove/ship');
const manifestPath = path.join(root, 'src/world/ship/lion-head-assets.ts');
const specs = [
  ['lite', 'lite.glb'],
  ['low', 'low.glb'],
  ['medium', 'medium.glb'],
  ['high', 'high.glb'],
];
const MAGIC = Buffer.from('CILION1\0', 'ascii');

function align2(n) {
  return n + (n & 1);
}

function sha256(data) {
  return createHash('sha256').update(data).digest('hex');
}

async function extract(name, file) {
  const io = new NodeIO();
  const doc = await io.read(path.join(inDir, file));
  const prim = doc.getRoot().listMeshes()[0].listPrimitives()[0];
  const pos = prim.getAttribute('POSITION').getArray();
  const normal = prim.getAttribute('NORMAL').getArray();
  const index = prim.getIndices().getArray();
  const vertexCount = pos.length / 3;
  const min = [Infinity, Infinity, Infinity];
  const max = [-Infinity, -Infinity, -Infinity];
  for (let i = 0; i < pos.length; i += 3) {
    for (let a = 0; a < 3; a++) {
      const v = pos[i + a];
      if (v < min[a]) min[a] = v;
      if (v > max[a]) max[a] = v;
    }
  }
  const center = min.map((v, i) => (v + max[i]) * 0.5);
  const radius = Math.max(...min.map((v, i) => (max[i] - v) * 0.5));
  const qp = new Int16Array(pos.length);
  for (let i = 0; i < pos.length; i++) {
    const axis = i % 3;
    qp[i] = Math.max(-32767, Math.min(32767, Math.round(((pos[i] - center[axis]) / radius) * 32767)));
  }
  const qn = new Int8Array(normal.length);
  for (let i = 0; i < normal.length; i++) qn[i] = Math.max(-127, Math.min(127, Math.round(normal[i] * 127)));
  const qi = Uint16Array.from(index);
  const headerBytes = 16;
  const posBytes = qp.byteLength;
  const normalOffset = headerBytes + posBytes;
  const indexOffset = align2(normalOffset + qn.byteLength);
  const out = Buffer.alloc(indexOffset + qi.byteLength);
  MAGIC.copy(out, 0);
  out.writeUInt32LE(vertexCount, 8);
  out.writeUInt32LE(qi.length, 12);
  Buffer.from(qp.buffer).copy(out, headerBytes);
  Buffer.from(qn.buffer).copy(out, normalOffset);
  Buffer.from(qi.buffer).copy(out, indexOffset);
  const fileName = `lion-${name}.bin`;
  await fs.writeFile(path.join(outDir, fileName), out);
  return {
    name,
    file: `/packs/testcove/ship/${fileName}`,
    center: center.map((v) => Number(v.toFixed(7))),
    radius: Number(radius.toFixed(7)),
    vertices: vertexCount,
    triangles: qi.length / 3,
    bytes: out.byteLength,
    sha256: sha256(out),
  };
}

await fs.mkdir(outDir, { recursive: true });
const lods = [];
for (const [name, file] of specs) lods.push(await extract(name, file));
const sourceSha = (
  await fs.readFile(path.join(root, 'tools/ship/source/lion-head/SHA256SUMS'), 'utf8')
).trim();
const body = `// Generated by tools/ship/build-lion-head.mjs from Poly Haven lion_head (CC0 1.0).\n// Source checksums:\n${sourceSha
  .split('\n')
  .map((line) => `// ${line}`)
  .join(
    '\n',
  )}\n\nexport interface LionHeadAsset {\n  file: string;\n  center: readonly [number, number, number];\n  radius: number;\n  vertices: number;\n  triangles: number;\n  bytes: number;\n  sha256: string;\n}\n\nexport const LION_HEAD_ASSETS = ${JSON.stringify(Object.fromEntries(lods.map(({ name, ...lod }) => [name, lod])), null, 2)} as const satisfies Record<string, LionHeadAsset>;\n`;
await fs.writeFile(manifestPath, body);
console.log(`wrote ${manifestPath}`);
for (const lod of lods)
  console.log(`${lod.name}: ${lod.triangles} tris, ${lod.vertices} verts, ${lod.bytes} bytes, ${lod.sha256}`);
